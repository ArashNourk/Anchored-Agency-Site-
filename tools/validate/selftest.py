"""End-to-end self-test with synthetic hardware.

A hidden "truth" calibration (different constants AND a different instrument
serial, i.e. different voice personalities) plays the role of the reference
Prophet. Its renders get an unknown pre-roll, a capture-chain gain and noise,
like real captures. The framework then measures, fits from the defaults and
reports. Passing shows that every fit group is identifiable from its tests and
that alignment, gain normalisation, voice-rotation matching and fitting work.
It does not show anything about the real instrument.
"""
import json
import os
import shutil

import numpy as np

from . import corpus, emulator, pipeline, wavio

TRUTH = {
    "osc.resetTimeSec": 6e-6,
    "filter.ssm.resOnsetKnob": 0.90, "filter.ssm.kMax": 4.9,
    "filter.cem.resOnsetKnob": 0.86, "filter.cem.kMax": 4.6,
    "filter.cutoffMinHz": 14.0, "filter.cutoffMaxHz": 19000.0, "filter.cem.cutoffScale": 1.06,
    "env.attackMaxSec": 6.0, "env.decayMaxSec": 9.0, "env.releaseMaxSec": 11.0, "env.timeTaper": 1.15,
    "pm.freqARangeSemis": 36.0, "pm.amountTaper": 2.3,
    "lfo.minHz": 0.05, "lfo.maxHz": 18.0, "mod.freqRangeSemis": 9.0,
}
HW_SERIAL = 777

# Constants that single-voice tests can only see through voice 1, whose own
# hidden personality (different serial) is folded into them. They must make
# the features pass but may differ from the global truth.
VOICE_CONFOUNDED = {"osc.resetTimeSec": 0.30}


def make_session(root, takes=3, seed=5, log=print):
    rng = np.random.default_rng(seed)
    truth = dict(TRUTH)
    for v in range(1, 11):
        truth[f"unit.v{v}.tuneCentsA"] = float(rng.normal(0, 1.5))
        truth[f"unit.v{v}.vcaGainDb"] = float(rng.normal(0, 0.4))
        truth[f"unit.v{v}.ampEnvTimeLn"] = float(rng.normal(0, 0.06))
    sdir = os.path.join(root, "synthetic-unit", "selftest")
    if os.path.exists(sdir):
        shutil.rmtree(sdir)
    os.makedirs(sdir)
    json.dump({"unit": "synthetic-unit", "session": "selftest", "firmware": "n/a", "synthetic": True,
               "note": "generated by tools.validate selftest; truth.json holds the hidden calibration"},
              open(os.path.join(sdir, "session.json"), "w"), indent=1)
    json.dump(truth, open(os.path.join(sdir, "truth.json"), "w"), indent=1)
    chain_gain = 0.7
    latency = 0.0073  # audio/MIDI path latency unknown to the pipeline
    preroll = {}
    for t in corpus.TESTS:
        x, fs = emulator.render(corpus.scenario_path(t), truth, serial=HW_SERIAL)
        os.makedirs(os.path.join(sdir, t["id"]))
        for n in range(1, takes + 1):
            sched = rng.uniform(0.3, 0.9)
            pre = int(round((sched + latency) * fs))
            preroll[f"{t['id']}/take{n}"] = pre / fs
            json.dump({"preroll_s": sched}, open(os.path.join(sdir, t["id"], f"take{n}.json"), "w"))
            noise = rng.normal(0, 10 ** (-85 / 20), pre + len(x) + fs // 2)
            y = noise.copy()
            y[pre:pre + len(x)] += x * chain_gain
            wavio.write(os.path.join(sdir, t["id"], f"take{n}.wav"), y, fs)
    json.dump(preroll, open(os.path.join(sdir, "preroll.json"), "w"), indent=1)
    log(f"synthetic session with {takes} takes per test: {sdir}")
    return sdir, truth


def run(root, log=print):
    sdir, truth = make_session(root, log=log)
    log("measuring captures")
    hw = pipeline.measure_session(sdir, log=log)
    meta = json.load(open(os.path.join(sdir, "session.json")))
    pre = json.load(open(os.path.join(sdir, "preroll.json")))
    al = [abs(a["offset_s"] - pre[f"{tid}/{a['file'][:-4]}"]) for tid, r in hw.items() for a in r["align"]]
    log(f"alignment error vs true pre-roll: max {1000 * max(al):.2f} ms, median {1000 * float(np.median(al)):.2f} ms")
    md0, s0 = pipeline.report(hw, {}, "Residuals before calibration", meta)
    log(f"before fitting: {s0['passed']}/{s0['features']} features within tolerance")
    log("fitting")
    fitted = pipeline.fit(hw, log=log)
    md1, s1 = pipeline.report(hw, fitted, "Residuals after calibration", meta)
    log(f"after fitting: {s1['passed']}/{s1['features']} features within tolerance")
    rows = ["| Parameter | Default | Truth | Recovered | Error |", "|---|---|---|---|---|"]
    d = emulator.defaults()
    worst = 0.0
    for k in TRUTH:
        err = (fitted.get(k, d[k]) - TRUTH[k]) / TRUTH[k]
        limit = VOICE_CONFOUNDED.get(k, 0.05)
        worst = max(worst, abs(err) / limit * 0.05)
        note = " (absorbs voice-1 personality)" if k in VOICE_CONFOUNDED else ""
        rows.append(f"| {k}{note} | {d[k]:.5g} | {TRUTH[k]:.5g} | {fitted.get(k, d[k]):.5g} | {100 * err:+.2f} % |")
    unit_err = max(abs(fitted.get(f"unit.v{v}.tuneCentsA", 0) - truth[f"unit.v{v}.tuneCentsA"]) for v in range(1, 11))
    rows.append(f"\nAlignment error against the true pre-roll: max {1000 * max(al):.2f} ms over {len(al)} takes.")
    rows.append(f"\nWorst unit-profile tuning error vs the hidden offsets: {unit_err:.3f} cents (includes the "
                "different serial's own Vintage residuals, which the profile is expected to absorb).")
    out = os.path.join(sdir, "selftest_report.md")
    with open(out, "w") as f:
        f.write("# Validation framework self-test\n\n" + (__doc__ or "") + "\n## Parameter recovery\n\n" +
                "\n".join(rows) + "\n\n" + md0.replace("# ", "## ", 1) + "\n\n" + md1.replace("# ", "## ", 1))
    emulator.write_calibration(os.path.join(sdir, "fitted.cal"), fitted)
    log(f"worst parameter recovery error {100 * worst:.2f} % of the 5 % limit scale; report: {out}")
    return s1, worst
